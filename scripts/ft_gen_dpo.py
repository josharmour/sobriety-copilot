#!/usr/bin/env python3
"""FT-C4: Generate DPO preference pairs from SFT quality-passed samples.

Reads finetune/gen/sft.filtered.jsonl (6,446 samples), produces
finetune/gen/dpo.jsonl (≥1,500 pairs).

Each pair:
  - prompt  = [system, user]  (from the filtered sample)
  - chosen  = [assistant]     (the filtered sample's kept answer)
  - rejected = [assistant]    (adversarially generated flawed variant)

Flaw taxonomy (5 types, spread evenly):
  1. fake_lived_experience  — answer claims personal recovery
  2. hotline_when_unneeded  — hotline/911 pushed on non-crisis question
  3. ignores_passages       — answers from generic knowledge, contradicts
                              or ignores provided gold passages
  4. bracket_citations      — [1]-style markers / filenames instead of titles
  5. rambles                — blows past the register's tone budget

Rejected answers are generated by dsv4 with adversarial prompts (temp=0.7),
then verified by dsv4 judge (temp=0).  Up to 3 tries, then skip.

Checkpointed & resumable — run under nohup.
"""

from __future__ import annotations

import json
import os
import random
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any

import requests

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO = Path(__file__).resolve().parent.parent
INPUT_PATH = REPO / "finetune" / "gen" / "sft.filtered.jsonl"
OUTPUT_PATH = REPO / "finetune" / "gen" / "dpo.jsonl"
CKPT_DIR = REPO / "finetune" / "gen" / ".dpo_checkpoint"

LLM_URL = "http://10.0.0.10:8002/v1/chat/completions"
LLM_MODEL = "deepseek-v4-flash"

CONCURRENCY = 12  # ≤16 per swarm rules
MAX_GEN_RETRIES = 3
MAX_JUDGE_RETRIES = 3

TARGET_PAIRS = 1500

_FLAW_TYPES = [
    "fake_lived_experience",
    "hotline_when_unneeded",
    "ignores_passages",
    "bracket_citations",
    "rambles",
]

# ---------------------------------------------------------------------------
# LLM helpers
# ---------------------------------------------------------------------------


def _call_dsv4(
    messages: list[dict],
    temperature: float = 0.7,
    max_tokens: int = 512,
) -> str | None:
    """Call dsv4 with thinking disabled. Returns content or None."""
    for attempt in range(MAX_GEN_RETRIES):
        try:
            resp = requests.post(
                LLM_URL,
                json={
                    "model": LLM_MODEL,
                    "messages": messages,
                    "temperature": temperature,
                    "max_tokens": max_tokens,
                    "chat_template_kwargs": {"thinking": False},
                },
                timeout=120,
            )
            if resp.status_code != 200:
                print(
                    f"  [dsv4 retry {attempt+1}] HTTP {resp.status_code}: {resp.text[:200]}",
                    file=sys.stderr,
                    flush=True,
                )
                time.sleep(2 * (attempt + 1))
                continue
            data = resp.json()
            content = data.get("choices", [{}])[0].get("message", {}).get("content", "")
            if content:
                return content.strip()
            print(f"  [dsv4 retry {attempt+1}] empty response", file=sys.stderr, flush=True)
        except requests.exceptions.Timeout:
            print(f"  [dsv4 retry {attempt+1}] timeout", file=sys.stderr, flush=True)
            time.sleep(5)
        except Exception as e:
            print(f"  [dsv4 retry {attempt+1}] {e}", file=sys.stderr, flush=True)
            time.sleep(5)
    return None


def _call_judge(system_prompt: str, user_prompt: str) -> str | None:
    """Call dsv4 as a judge (temp=0, no thinking). Returns YES/NO or None."""
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]
    for attempt in range(MAX_JUDGE_RETRIES):
        try:
            resp = requests.post(
                LLM_URL,
                json={
                    "model": LLM_MODEL,
                    "messages": messages,
                    "temperature": 0.0,
                    "max_tokens": 256,
                    "chat_template_kwargs": {"thinking": False},
                },
                timeout=120,
            )
            if resp.status_code != 200:
                print(
                    f"  [judge retry {attempt+1}] HTTP {resp.status_code}",
                    file=sys.stderr,
                    flush=True,
                )
                time.sleep(2 * (attempt + 1))
                continue
            data = resp.json()
            content = data.get("choices", [{}])[0].get("message", {}).get("content", "")
            if not content:
                if attempt < MAX_JUDGE_RETRIES - 1:
                    continue
                return None
            # Extract YES or NO
            upper = content.upper()
            if "YES" in upper:
                return "YES"
            if "NO" in upper:
                return "NO"
            if attempt < MAX_JUDGE_RETRIES - 1:
                continue
            return None
        except Exception as e:
            print(f"  [judge error] {e}", file=sys.stderr, flush=True)
            if attempt < MAX_JUDGE_RETRIES - 1:
                time.sleep(3)
                continue
            return None
    return None


