def load_jsonl(path: str, max_rows: int | None = None) -> list[dict]:
    """Load JSONL, optionally limiting to *max_rows*."""
    rows: list[dict] = []
    with open(path) as f:
        for i, line in enumerate(f):
            if max_rows is not None and i >= max_rows:
                break
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


FLAW_CATEGORIES = [
    "fake_lived_experience",
    "hotline_when_unneeded",
    "ignores_passages",
    "bracket_citations",
    "rambles",
]

SYSTEM_PROMPT = (
    "You are a knowledgeable, direct guide to recovery literature. "
    "Answer in two to four short sentences based on the passages provided."
)


def fabricate_dummy_dpo_pairs(count: int = 200) -> list[dict]:
    """Generate schema-identical dummy DPO pairs for CPU-side validation.

    Each pair has a shared prompt (system + user), a chosen (flawless)
    assistant response, and a rejected (flawed) assistant response labeled
    by ``meta.flaw``.

    The schema matches what C4 will produce in finetune/gen/dpo.jsonl.
    No real data is required — all content is synthetic placeholders.
    """
    import random

    user_questions = [
        "How do I work Step One?",
        "What does the Big Book say about resentment?",
        "I'm struggling with the concept of a Higher Power.",
        "How can I make amends when the person won't talk to me?",
        "What is the difference between the steps and the traditions?",
        "I'm having cravings tonight — what should I do?",
        "Can you explain what 'rigorous honesty' means?",
        "Why is prayer mentioned in step eleven?",
    ]

    dummy_chosen_text = (
        "Based on the Big Book, Step One means admitting we were powerless "
        "over alcohol and that our lives had become unmanageable. "  # noqa: E501
        "This is the foundation — without surrender, the other steps cannot work."
    )

    samples: list[dict] = []
    for _ in range(count):
        flaw = random.choice(FLAW_CATEGORIES)
        question = random.choice(user_questions)

        # Build flawed rejected text based on flaw category
        if flaw == "fake_lived_experience":
            rejected_text = (
                "When I was drinking, I used to wake up not knowing where I was. "
                "My sponsor told me to call him every day. [FAKE-LIVED-EXPERIENCE]"
            )
        elif flaw == "hotline_when_unneeded":
            rejected_text = (
                "You should call the suicide hotline right now. " + dummy_chosen_text
            )
        elif flaw == "ignores_passages":
            rejected_text = (
                "I don't need any book to tell me what to do. Just stop drinking — "
                "it's that simple."
            )
        elif flaw == "bracket_citations":
            rejected_text = (
                dummy_chosen_text.replace("Big Book", "[BB]")
                .replace("Step One", "[S1]")
            )
        elif flaw == "rambles":
            rejected_text = (
                "Well, it's complicated because everyone's journey is different "
                "and what works for one person might not work for another and "
                "there are many paths to recovery and you have to find what "
                "works for you personally..."
            )
        else:
            rejected_text = dummy_chosen_text

        samples.append({
            "prompt": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": question},
            ],
            "chosen": [
                {"role": "assistant", "content": dummy_chosen_text},
            ],
            "rejected": [
                {"role": "assistant", "content": rejected_text},
            ],
            "meta": {
                "flaw": flaw,
            },
        })

    return samples


def split_dataset(
    rows: list[dict],
    train_frac: float = 0.98,
    stratify_key: str = "flaw",
) -> tuple[list[dict], list[dict]]:
    """Stratified train/val split by flaw category."""
    import collections

    groups: dict[str, list[dict]] = collections.defaultdict(list)
    for r in rows:
        key = str(r.get("meta", {}).get(stratify_key, "unknown"))
        groups[key].append(r)

    train_all: list[dict] = []
    val_all: list[dict] = []
    for key, group in groups.items():
        group.sort(key=lambda x: json.dumps(x, sort_keys=True))  # deterministic
        n_train = max(1, int(len(group) * train_frac))
        train_all.extend(group[:n_train])
        val_all.extend(group[n_train:])

    # Shuffle deterministically
    import random
    rng = random.Random(42)
    rng.shuffle(train_all)
    rng.shuffle(val_all)
    return train_all, val_all


