def load_config(path: str) -> dict[str, Any]:
    import yaml
    with open(path) as f:
        cfg = yaml.safe_load(f)
    if not isinstance(cfg, dict):
        raise ValueError(
            f"Config {path} must be a top-level dict, got {type(cfg).__name__}"
        )
    return cfg


