def load_tokenizer(model_name: str):
    """Load tokenizer (config-only — no model weights)."""
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(
        model_name,
        trust_remote_code=True,
    )
    return tok


def format_messages(messages: list[dict], tokenizer) -> str:
    """Apply chat template to a list of message dicts."""
    return tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=False,
    )


def tokenize_dpo_pair(
    prompt_text: str,
    chosen_text: str,
    rejected_text: str,
    tokenizer,
    seq_len: int,
) -> dict[str, list[int] | list[list[int]]]:
    """Tokenize a single DPO triple (prompt, chosen, rejected).

    Returns a dict with:
        prompt_input_ids, prompt_attention_mask,
        chosen_input_ids, chosen_labels,
        rejected_input_ids, rejected_labels

    Labels mask out the prompt tokens (set to -100) so the loss is computed
    only on the response tokens.
    """
    # Tokenize prompt
    prompt_enc = tokenizer(
        prompt_text,
        truncation=True,
        max_length=seq_len,
        padding=False,
        return_attention_mask=False,
    )
    prompt_ids = prompt_enc["input_ids"]

    # Tokenize chosen response
    chosen_enc = tokenizer(
        chosen_text,
        truncation=True,
        max_length=seq_len - len(prompt_ids),
        padding=False,
        return_attention_mask=False,
    )
    chosen_ids = prompt_ids + chosen_enc["input_ids"]
    chosen_labels = ([-100] * len(prompt_ids)) + chosen_enc["input_ids"]

    # Truncate if needed
    if len(chosen_ids) > seq_len:
        chosen_ids = chosen_ids[:seq_len]
        chosen_labels = chosen_labels[:seq_len]

    # Tokenize rejected response
    rejected_enc = tokenizer(
        rejected_text,
        truncation=True,
        max_length=seq_len - len(prompt_ids),
        padding=False,
        return_attention_mask=False,
    )
    rejected_ids = prompt_ids + rejected_enc["input_ids"]
    rejected_labels = ([-100] * len(prompt_ids)) + rejected_enc["input_ids"]

    if len(rejected_ids) > seq_len:
        rejected_ids = rejected_ids[:seq_len]
        rejected_labels = rejected_labels[:seq_len]

    prompt_attention = [1] * len(prompt_ids)

    return {
        "prompt_input_ids": prompt_ids,
        "prompt_attention_mask": prompt_attention,
        "chosen_input_ids": chosen_ids,
        "chosen_labels": chosen_labels,
        "rejected_input_ids": rejected_ids,
        "rejected_labels": rejected_labels,
    }


