def _build_negative_answer(question: str) -> str:
    """Produce a refusal for a negative-row question."""
    q_lower = question.lower()
    # Check known patterns
    for key, answer in _NEGATIVE_ANSWERS.items():
        if key in q_lower:
            return answer

    # Fallback by question type
    if any(w in q_lower for w in ["doctor", "medical", "medication", "prescribe", "dose",
                                    "dosage", "withdrawal", "detox", "liver", "suboxone",
                                    "naltrexone", "antabuse", "ibuprofen", "antidepressant",
                                    "benzodiazepine"]):
        return _NEGATIVE_ANSWERS["naltrexone"]

    if any(w in q_lower for w in ["laptop", "computer", "wifi", "wi-fi", "car", "rust",
                                    "skillet", "sourdough", "tree sap", "bread"]):
        return _NEGATIVE_DEFAULT

    return _NEGATIVE_DEFAULT


# ---------------------------------------------------------------------------
# Reference answer generation
# ---------------------------------------------------------------------------

_SYSTEM_PROMPT = (
    "You are an expert in recovery literature who writes reference answers for evaluating "
    "a RAG system. Your task is to write a concise, accurate answer grounded in the provided "
    "source text(s). Strict rules:\n"
    "1. Answer in natural prose — NO bracketed citations, NO footnotes, NO markdown.\n"
    "2. Name the work(s) by their exact title(s) in the body of the answer.\n"
    "3. Maximum 120 words.\n"
    "4. Do NOT invent details not present in the source texts.\n"
    "5. Do NOT use first-person ('I', 'my', 'we') — write as an authoritative summary.\n"
    "6. Do NOT create fake lived experience.\n"
    "7. Compose a single coherent paragraph."
)


def _build_reference_answer(
    question: str,
    source_texts: list[tuple[str, str, str]],
    titles: dict[str, str],
) -> str | None:
    """Call dsv4 to generate a reference answer given source blocks.

    Args:
        question: The question text.
        source_texts: List of (doc_id, block_id, text) for each gold block.
        titles: doc_id → display title mapping.

    Returns:
        The answer string, or None on failure.
    """
    # Build context block
    context_parts = []
    seen_docs: set[str] = set()
    doc_refs: list[str] = []

    for doc_id, block_id, text in source_texts:
        title = titles.get(doc_id, doc_id)
        if doc_id not in seen_docs:
            doc_refs.append(title)
            seen_docs.add(doc_id)
        context_parts.append(
            f"--- Source: {title} ({doc_id}/{block_id}) ---\n{text}"
        )

    context = "\n\n".join(context_parts)

    prompt = (
        f"Using the following source text(s), write a concise reference answer "
        f"(≤120 words, one paragraph) to the question below.\n\n"
        f"QUESTION: {question}\n\n"
        f"SOURCE TEXTS:\n{context}\n\n"
        f"IMPORTANT: Your answer must name the work(s) by their exact titles "
        f"({', '.join(doc_refs)}) in natural prose. Do not use any bracketed "
        f"citations or markdown. Stay within 120 words."
    )

    return _call_dsv4(prompt, system=_SYSTEM_PROMPT)


# ---------------------------------------------------------------------------
# Checkpoint helpers
# ---------------------------------------------------------------------------

def _load_checkpoint() -> dict[str, str]:
    """Load completed entries: id → JSON line. Resumes from previous run."""
    completed: dict[str, str] = {}

    # First, check the checkpoint directory
    if CKPT_DIR.is_dir():
        for ckpt_file in sorted(CKPT_DIR.iterdir()):
            if ckpt_file.suffix == ".jsonl":
                with open(ckpt_file) as f:
                    for line in f:
                        line = line.strip()
                        if line:
                            row = json.loads(line)
                            completed[row["id"]] = line

    # Also load any existing gold.jsonl to avoid re-gen
    if GPATH.is_file():
        with open(GPATH) as f:
            for line in f:
                line = line.strip()
                if line:
                    row = json.loads(line)
                    completed[row["id"]] = line

    return completed


def _save_checkpoint_row(row: dict, batch_id: str):
    """Save a single completed row to a checkpoint file."""
    CKPT_DIR.mkdir(parents=True, exist_ok=True)
    ckpt_file = CKPT_DIR / f"batch_{batch_id}.jsonl"
    with open(ckpt_file, "a") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def _assemble_final(completed: dict[str, str], all_ids: list[str]):
    """Write gold.jsonl from completed entries in the correct order."""
    with open(GPATH, "w") as f:
        for qid in all_ids:
            line = completed.get(qid)
            if line:
                f.write(line + "\n")
            else:
                print(f"WARNING: missing {qid} in completed set", file=sys.stderr)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    # Load questions
    questions: list[dict[str, Any]] = []
    with open(QPATH) as f:
        for line in f:
            line = line.strip()
            if line:
                questions.append(json.loads(line))

    print(f"Loaded {len(questions)} questions", flush=True)

    # Load titles
    titles = _load_doc_titles()
    print(f"Loaded {len(titles)} doc titles from manifest", flush=True)

    # Load checkpoint
    completed = _load_checkpoint()
    print(f"Already completed: {len(completed)} rows", flush=True)

    # Determine which questions need generation
    all_ids = [q["id"] for q in questions]
    todo = [q for q in questions if q["id"] not in completed]
    print(f"Remaining: {len(todo)} questions", flush=True)

    if not todo:
        print("Nothing to do — all rows already completed.", flush=True)
        # Still assemble final
        _assemble_final(completed, all_ids)
        print(f"Gold written to {GPATH}", flush=True)
        return

    # Process in batches with concurrency
    batch_size = CONCURRENCY
    total_batches = (len(todo) + batch_size - 1) // batch_size

    for batch_idx in range(total_batches):
        batch = todo[batch_idx * batch_size : (batch_idx + 1) * batch_size]
        batch_label = f"{batch_idx+1}/{total_batches}"
        print(f"\nBatch {batch_label} ({len(batch)} questions)", flush=True)

        def process_one(q: dict) -> tuple[str, dict | None]:
            """Process a single question. Returns (id, gold_row_dict or None)."""
            kind = q["kind"]
            qid = q["id"]
            question = q["question"]

            try:
                gold_doc_ids, gold_block_ids = _get_gold_spec(q)

                if kind == "negative":
                    answer = _build_negative_answer(question)
                    row = {
                        "id": qid,
                        "gold_doc_ids": [],
                        "gold_block_ids": [],
                        "reference_answer": answer,
                    }
                    return qid, row

                # Non-negative: fetch block texts
                doc_block_pairs = list(zip(gold_doc_ids, gold_block_ids))
                texts = _fetch_blocks(doc_block_pairs)

                source_texts: list[tuple[str, str, str]] = []
                for doc_id, block_id in doc_block_pairs:
                    text = texts.get((doc_id, block_id), "")
                    if not text:
                        print(f"  WARN: {qid} — no text for {doc_id}/{block_id}",
                              file=sys.stderr)
                    source_texts.append((doc_id, block_id, text))

                # Generate reference answer
                answer = _build_reference_answer(question, source_texts, titles)
                if answer is None:
                    print(f"  FAIL: {qid} — LLM call failed after retries",
                          file=sys.stderr)
                    return qid, None

                row = {
                    "id": qid,
                    "gold_doc_ids": gold_doc_ids,
                    "gold_block_ids": gold_block_ids,
                    "reference_answer": answer,
                }
                return qid, row

            except Exception as e:
                print(f"  ERROR: {qid} — {e}", file=sys.stderr)
                return qid, None

        # Run batch concurrently
        with ThreadPoolExecutor(max_workers=CONCURRENCY) as pool:
            futures = {pool.submit(process_one, q): q["id"] for q in batch}
            for future in as_completed(futures):
                qid, row = future.result()
                if row is not None:
                    completed[qid] = json.dumps(row, ensure_ascii=False)
                    _save_checkpoint_row(row, f"batch{batch_idx:04d}")

        # Progress
        done = sum(1 for qid in all_ids if qid in completed)
        print(f"  Progress: {done}/{len(all_ids)}", flush=True)

    # Assemble final gold.jsonl in question order
    _assemble_final(completed, all_ids)
    print(f"\nDone! {len(completed)}/{len(all_ids)} rows written to {GPATH}",
          flush=True)

    # Report any failures
    failed = [qid for qid in all_ids if qid not in completed]
    if failed:
        print(f"FAILED ({len(failed)}): {failed}", file=sys.stderr)


if __name__ == "__main__":
    main()
