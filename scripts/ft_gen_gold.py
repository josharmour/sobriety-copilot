#!/usr/bin/env python3
"""FT-A2: Generate gold.jsonl — reference answers + gold citations.

Reads finetune/eval/questions.jsonl (256 rows), produces
finetune/eval/gold.jsonl with one entry per question:

    {id, gold_doc_ids[], gold_block_ids[], reference_answer}

For non-negative rows: gold = source blocks from the question;
reference_answer is generated by dsv4 WITH the block text in-context,
≤120 words, names the work by exact title, no bracketed citations.

For negative rows: gold_doc_ids=[], gold_block_ids=[], reference_answer
is a short honest refusal.

Checkpointed & resumable — run under nohup.
"""

from __future__ import annotations

import json
import os
import sys
import time
import zipfile
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any

import requests

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO = Path(__file__).resolve().parent.parent
QPATH = REPO / "finetune" / "eval" / "questions.jsonl"
GPATH = REPO / "finetune" / "eval" / "gold.jsonl"
CKPT_DIR = REPO / "finetune" / "eval" / ".gold_checkpoint"
PACK = REPO / "packs" / "library-v1.scpack"
CACHE_DB = REPO / "finetune" / "cache" / "search.db"

LLM_URL = "http://10.0.0.10:8002/v1/chat/completions"
LLM_MODEL = "deepseek-v4-flash"

CONCURRENCY = 8
MAX_RETRIES = 3

# ---------------------------------------------------------------------------
# Corpus access
# ---------------------------------------------------------------------------

def _ensure_corpus_db() -> Path:
    """Extract search.db if needed."""
    if CACHE_DB.exists():
        return CACHE_DB
    CACHE_DB.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(PACK, "r") as zf:
        with zf.open("search.db") as src, open(CACHE_DB, "wb") as dst:
            import shutil
            shutil.copyfileobj(src, dst)
    return CACHE_DB


def _load_doc_titles() -> dict[str, str]:
    """Load doc_id → title from pack manifest."""
    z = zipfile.ZipFile(PACK)
    m = json.loads(z.read("manifest-index.json"))
    items = m if isinstance(m, list) else m.get("docs") or []
    return {d["doc_id"]: d["title"] for d in items}


def _fetch_blocks(doc_blocks: list[tuple[str, str]]) -> dict[tuple[str, str], str]:
    """Fetch block texts from corpus DB.

    Args:
        doc_blocks: list of (doc_id, block_id) tuples.

    Returns:
        dict mapping (doc_id, block_id) → text.
    """
    import sqlite3
    db_path = _ensure_corpus_db()
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    result: dict[tuple[str, str], str] = {}
    try:
        for doc_id, block_id in doc_blocks:
            row = conn.execute(
                "SELECT text FROM blocks WHERE doc_id=? AND block_id=?",
                (doc_id, block_id),
            ).fetchone()
            if row:
                result[(doc_id, block_id)] = row[0]
            else:
                result[(doc_id, block_id)] = ""
    finally:
        conn.close()
    return result


# ---------------------------------------------------------------------------
# Gold row builder
# ---------------------------------------------------------------------------

def _get_gold_spec(q: dict) -> tuple[list[str], list[str]]:
    """Determine (gold_doc_ids, gold_block_ids) for a question.

    For crosswork: use source_doc_ids aligned with source_block_ids.
    For negative: both empty.
    For everything else: source_doc_id + source_block_ids.
    """
    kind = q["kind"]
    if kind == "negative":
        return [], []

    if kind == "crosswork":
        docs = q.get("source_doc_ids", [])
        blocks = q.get("source_block_ids", [])
        # Ensure aligned — spec says docs[i] pairs with blocks[i]
        if len(docs) == len(blocks):
            return docs, blocks
        # Fallback: if crosswork has 2 blocks but docs field has issues,
        # use source_doc_id for the first doc, source_doc_ids for both
        primary = q.get("source_doc_id")
        if primary and docs:
            return [primary, docs[1]] if len(docs) > 1 else [primary], blocks
        return docs, blocks

    # Standard: source_doc_id + source_block_ids
    doc_id = q.get("source_doc_id")
    blocks = q.get("source_block_ids", [])
    if doc_id and blocks:
        return [doc_id] * len(blocks), blocks
    return [], []


# ---------------------------------------------------------------------------
# LLM call
# ---------------------------------------------------------------------------

def _call_dsv4(prompt: str, system: str = "") -> str | None:
    """Call dsv4 with thinking disabled, temp 0.7. Returns content or None."""
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    for attempt in range(MAX_RETRIES):
        try:
            resp = requests.post(
                LLM_URL,
                json={
                    "model": LLM_MODEL,
                    "messages": messages,
                    "temperature": 0.7,
                    "max_tokens": 512,
                    "chat_template_kwargs": {"thinking": False},
                },
                timeout=120,
            )
            if resp.status_code != 200:
                print(f"  [retry {attempt+1}] HTTP {resp.status_code}: {resp.text[:200]}",
                      file=sys.stderr)
                time.sleep(2 * (attempt + 1))
                continue
            data = resp.json()
            content = data.get("choices", [{}])[0].get("message", {}).get("content", "")
            if content:
                return content.strip()
            print(f"  [retry {attempt+1}] empty response", file=sys.stderr)
        except requests.exceptions.Timeout:
            print(f"  [retry {attempt+1}] timeout", file=sys.stderr)
            time.sleep(5)
        except Exception as e:
            print(f"  [retry {attempt+1}] {e}", file=sys.stderr)
            time.sleep(5)
    return None


